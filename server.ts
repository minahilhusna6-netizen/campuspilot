// 6. Camera Scan Notes / OCR Analysis
app.post("/api/gemini/ocr-scan", async (req, res) => {
  try {
    const { imageBase64, mimeType } = req.body;
    const ai = getGenAI();

    if (!ai) {
      return res.status(500).json({
        success: false,
        error: "GEMINI_API_KEY environment variable is missing on the server.",
      });
    }

    if (!imageBase64) {
      return res.status(400).json({ success: false, error: "No image provided." });
    }

    const base64Data = imageBase64.includes(",") ? imageBase64.split(",")[1] : imageBase64;
    const imagePart = {
      inlineData: {
        data: base64Data,
        mimeType: mimeType || "image/jpeg",
      },
    };

    const textPart = {
      text: "Perform OCR on these scanned handwritten/printed study notes or whiteboard photo. Extract all readable text accurately, summarize key takeaways, and list action items. Return JSON with keys: extractedText, summary, actionItems (array of strings)."
    };

    const response = await ai.models.generateContent({
      model: "gemini-2.5-flash",
      contents: { parts: [imagePart, textPart] },
      config: { responseMimeType: "application/json" }
    });

    const data = JSON.parse(response.text || "{}");
    return res.json({ success: true, ...data });
  } catch (error: any) {
    console.error("Error in /api/gemini/ocr-scan:", error);
    return res.status(500).json({ success: false, error: error.message || "Failed image OCR analysis" });
  }
});

// Serve frontend with Vite in dev mode or static files in production
async function startServer() {
  if (process.env.NODE_ENV !== "production") {
    const vite = await createViteServer({
      server: { middlewareMode: true },
      appType: "spa",
    });
    app.use(vite.middlewares);
  } else {
    const distPath = path.join(process.cwd(), "dist");
    app.use(express.static(distPath));
    app.get("*", (_req, res) => {
      res.sendFile(path.join(distPath, "index.html"));
    });
  }

  app.listen(PORT, "0.0.0.0", () => {
    console.log(`[CampusPilot] Server running on http://0.0.0.0:${PORT}`);
  });
}

startServer();
